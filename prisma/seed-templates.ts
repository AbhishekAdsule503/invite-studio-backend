async function seed() {
  const db = prisma as any;
  for (const tpl of initialTemplates) {
    await db.template.upsert({
      where: { slug: tpl.slug },
      update: tpl,
      create: tpl,
    });
  }
  console.log(`Seeded ${initialTemplates.length} templates.`);
  await prisma.$disconnect();
}


seed().catch((e) => {
  console.error(e);
  process.exit(1);
});
